window.BLOG.search = function (q) {
  const s = (q || '').trim().toLowerCase();
  if (!s) return [];
  return window.BLOG.articles.filter(a => [a.title, a.excerpt, a.cat, ...(a.tags || [])].join(' ').toLowerCase().includes(s));
};

